def build_trampoline_map():
    data = IMAGE.read_bytes()
    assert len(data) == 2_031_616
    assert sha256(data).hexdigest() == SHA256
    print(f"Building trampoline map from stock F08: {SHA256}")
    
    tramp_map = {}
    
    # Parse all banks looking for bank-switch patterns
    # Pattern: MOV direct,#imm (0x75) where direct in 0x60-0x7f, followed by LJMP to >=0x8000
    for bank in range(20):
        seg = data[bank*BANK_SIZE:(bank+1)*BANK_SIZE]
        i = 0
        while i < len(seg) - 5:
            op = seg[i]
            if op == 0x75 and i+2 < len(seg) and 0x60 <= seg[i+1] <= 0x7f:
                # look ahead for LJMP (0x02)
                for j in range(i+3, min(i+10, len(seg)-2)):
                    if seg[j] == 0x02:
                        tgt = (seg[j+1] << 8) | seg[j+2]
                        if tgt >= 0x8000:
                            # This is a trampoline
                            tramp_addr = f"{bank}:{i:04X}"
                            # Try to determine target bank from context
                            tramp_map[tramp_addr] = {
                                "source_bank": bank,
                                "source_addr": i,
                                "target_bank": None,  # to be determined
                                "target_addr": tgt,
                                "pattern": seg[i:j+3].hex(),
                                "sfr": f"{seg[i+1]:02X}",
                                "sfr_val": f"{seg[i+2]:02X}"
                            }
                        break
            i += OPLEN.get(op, 1)
    
    # Also look for the shared stub patterns
    # Common trampoline patterns from audit scripts
    common_patterns = [
        (0x0C54, "e5 52 54 1f 23 23 c0 e0 74 50 c0 e0 c0 82 c0 83 02 50 30"),
        (0x0BBC, "e5 52 54 1f 23 23 c0 e0 74 50 c0 e0 c0 82 c0 83 02 50 10"),
        (0x0BA9, "e5 52 54 1f 23 23 c0 e0 74 50 c0 e0 c0 82 c0 83 02 50 0c"),
        (0x0BF5, "e5 52 54 1f 23 23 c0 e0 74 50 c0 e0 c0 82 c0 83 02 50 1c"),
        (0x0C67, "e5 52 54 1f 23 23 c0 e0 74 50 c0 e0 c0 82 c0 83 02 50 34"),
        (0x0C7A, "e5 52 54 1f 23 23 c0 e0 74 50 c0 e0 c0 82 c0 83 02 50 38"),
    ]
    
    for addr, pattern in common_patterns:
        if data[addr:addr+len(bytes.fromhex(pattern))] == bytes.fromhex(pattern):
            tramp_map[f"0:{addr:04X}"] = {
                "type": "shared_stub",
                "pattern": pattern
            }
    
    # Write to file
    with open(OUT, 'w') as f:
        json.dump(tramp_map, f, indent=2)
    
    print(f"Wrote {len(tramp_map)} trampoline entries to {OUT}")

if __name__ == "__main__":
    build_trampoline_map()
